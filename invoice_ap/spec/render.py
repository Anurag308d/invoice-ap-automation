"""Render the data dictionary as deterministic JSON and Markdown."""
from __future__ import annotations

import json
from dataclasses import asdict

from ..common import enums
from . import CORE_ENTITIES, SPEC_VERSION, TABLES, TYPES
from .model import ORIGINS

_VOCAB = {name: value for name, value in sorted(vars(enums).items())
          if name.isupper() and isinstance(value, tuple) and value and isinstance(value[0], str)}
_REVERSE = {value: name for name, value in _VOCAB.items()}


def _as_of() -> str:
    from ..common.policy import load_policy
    return load_policy().raw["policy"]["as_of_date"]


def to_dict() -> dict:
    return {
        "spec_version": SPEC_VERSION,
        "types": {k: {"representation": v[0], "sqlite": v[1]} for k, v in TYPES.items()},
        "origins": list(ORIGINS),
        "core_entities": list(CORE_ENTITIES),
        "tables": [{
            "name": t.name, "layer": t.layer, "writer": t.writer, "entity": t.entity,
            "description": t.description, "grain": t.grain, "file": t.file,
            "primary_key": list(t.primary_key),
            "unique_together": [list(u) for u in t.unique_together],
            "fields": [{k: (list(v) if isinstance(v, tuple) else v) for k, v in asdict(f).items()}
                       for f in t.fields],
        } for t in TABLES],
    }


def to_json() -> str:
    return json.dumps(to_dict(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _cell(value: str) -> str:
    """Escape a table cell: pipes everywhere, '<' outside code spans (GitHub would treat
    `<po_id>` as an HTML tag and hide it)."""
    parts = value.replace("|", "\\|").replace("\n", " ").split("`")
    return "`".join(p if i % 2 else p.replace("<", "&lt;") for i, p in enumerate(parts))


def _allowed(f) -> str:
    if f.allowed:
        name = _REVERSE.get(tuple(f.allowed))
        if len(f.allowed) > 6 and name:
            return f"`enums.{name}` ({len(f.allowed)} values)"
        return ", ".join(f.allowed)
    parts = []
    if f.pattern:
        parts.append(f"`{f.pattern}`")
    if f.min_value or f.max_value:
        parts.append(f"range [{f.min_value or '-inf'}, {f.max_value or 'inf'}]")
    return "; ".join(parts) or "-"


def _rule(f) -> str:
    parts = ["**Reporting only, never an engine input.**"] if f.reporting_only else []
    if f.fk:
        parts.append(f"FK -> `{f.fk}`")
    if f.derivation:
        parts.append(f"= {f.derivation}")
    if f.rule and not (f.fk and f.rule == f"must exist in {f.fk}"):
        parts.append(f.rule)
    if f.required_when:
        parts.append(f"required when {f.required_when}")
    return "; ".join(parts) or "-"


def to_markdown() -> str:
    out = [
        "# Data dictionary",
        "",
        "<!-- Generated by `python -m invoice_ap docs` from invoice_ap/spec/*.py. Do not edit by hand; "
        "tests/test_spec.py fails when this file is stale. -->",
        "",
        f"Spec version {SPEC_VERSION}. Machine-readable copy: `invoice_ap/spec/data_dictionary.json` "
        "(same content). Every field lists type, required/optional, allowed values, unit, uniqueness, "
        "validation rule, description and origin (source or derived), as assignment Step 1 asks.",
        "",
        "## Conventions",
        "",
        "| Logical type | Representation in CSV / JSON | SQLite affinity |",
        "|---|---|---|",
        *[f"| `{k}` | {v[0]} | {v[1]} |" for k, v in TYPES.items()],
        "",
        "Origins: `source` = generated or printed as-is; `derived` = computed from other records by the "
        "formula shown (never generated independently, Step 6); `assigned` = deterministic ID or sequence; "
        "`captured` = extracted by the engine from a document; `decided` = set by an engine or oracle "
        "rule (rule IDs in docs/business_rules.md). Empty CSV cell = null. `*_as_of` and `snapshot_*` "
        f"fields are evaluated at `policy.as_of_date` ({_as_of()}). `snapshot_*` columns in engine-readable "
        "layers are reporting only: the engine never reads them (ADR-038).",
        "",
        "## Tables",
        "",
        "| Table | Layer | Written by | Core entity | Grain | Primary key | File |",
        "|---|---|---|---|---|---|---|",
    ]
    for t in TABLES:
        out.append(f"| [`{t.name}`](#{t.name}) | {t.layer} | {t.writer} | {t.entity or '-'} | {t.grain} "
                   f"| {', '.join(t.primary_key)} | `data/<scale>/{t.file}` |")
    for t in TABLES:
        out += ["", f"### {t.name}", "", _cell(t.description), "",
                f"- Layer: `{t.layer}` (written by the {t.writer}); file `data/<scale>/{t.file}`",
                f"- Grain: {t.grain}",
                f"- Primary key: `{', '.join(t.primary_key)}`"]
        if t.entity:
            out.append(f"- Assignment core entity: **{t.entity}**")
        if t.unique_together:
            out.append("- Unique together: " + "; ".join(f"`({', '.join(u)})`" for u in t.unique_together))
        out += ["", "| Field | Type | Required | Allowed values / format | Unit | Unique | Origin "
                    "| Validation rule / derivation | Description |",
                "|---|---|---|---|---|---|---|---|---|"]
        for f in t.fields:
            req = "yes" if f.required else ("conditional" if f.required_when else "no")
            out.append("| " + " | ".join(_cell(c) for c in (
                f"`{f.name}`", f.type, req, _allowed(f), f.unit or "-", "yes" if f.unique else "-",
                f.origin, _rule(f), f.description)) + " |")
    out += ["", "## Controlled vocabularies", "",
            "Defined once in `invoice_ap/common/enums.py`.", ""]
    for name, values in _VOCAB.items():
        out.append(f"- `{name}`: {', '.join(values)}")
    return "\n".join(out) + "\n"
