"""One generator run: plan -> baseline (validated) -> injections -> oracle -> validated output."""
from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path

from ..common.paths import DEFAULT_DATA_DIR, DEFAULT_POLICY, LAYERS
from ..common.policy import Policy, load_policy
from ..quality.quick import validate
from ..report.distribution import summarize, to_markdown
from . import params as P
from .allocation import Allocation, allocate
from .oracle import label
from .planner import Plan, make_plan
from .tables import Dataset, materialize
from .world import build_world
from .writer import as_strings, json_bytes, json_rows, write_file, write_dataset


class GenerationError(RuntimeError):
    """The baseline or the final dataset failed its self-checks."""


@dataclass
class BuildResult:
    alloc: Allocation
    plan: Plan
    baseline: Dataset
    final: Dataset
    baseline_report: dict
    report: dict
    files: dict[str, dict]
    out: Path | None


def _strings(tables: dict) -> dict:
    return {name: as_strings(name, rows) for name, rows in tables.items()}


def _report_md(report: dict, title: str) -> str:
    lines = [f"# {title}", "", f"Status: **{report['status']}** - violations {report['violations']}, "
             f"labelled defects reported as expected {report['labelled']}", "",
             "| Check | Status | Violations | Labelled (expected) | Note |", "|---|---|---|---|---|"]
    lines += [f"| {i['check']} | {i['status']} | {i['violations']} | {i['labelled']} | {i['note']} |"
              for i in report["checks"]]
    return "\n".join(lines) + "\n"


def generate(scale: str = "starter", seed: int = P.DEFAULT_SEED, out: Path | str | None = None,
             policy: Policy | None = None, write: bool = True) -> BuildResult:
    policy = policy or load_policy(DEFAULT_POLICY)
    alloc = allocate(scale)
    plan = make_plan(build_world(alloc, policy.raw, seed))
    baseline = materialize(plan, "baseline", policy.version)
    base_report = validate(_strings(baseline.tables), policy)
    if base_report["status"] != "pass" or base_report["labelled"]:
        raise GenerationError(f"baseline is not clean: {base_report}")
    final = materialize(plan, "final", policy.version)
    gt, gtl = label(final, policy)                 # raises OracleMismatch on any intent mismatch
    final.tables["ground_truth"], final.tables["ground_truth_line"] = gt, gtl
    report = validate(_strings(final.tables), policy, alloc)
    if report["status"] != "pass":
        raise GenerationError(f"final dataset failed self-checks: {[i for i in report['checks'] if i['violations']]}")
    files: dict[str, dict] = {}
    root = None
    if write:
        root = Path(out) if out else DEFAULT_DATA_DIR / alloc.scale
        for layer in LAYERS:                          # only the folders this build owns
            shutil.rmtree(root / layer, ignore_errors=True)
        meta = {"seed": seed, "scale": alloc.scale, "factor": str(alloc.factor), "policy_id": policy.id,
                "policy_version": policy.version, "generator_version": P.GENERATOR_VERSION,
                "invoices": len(gt), "invoice_lines": len(gtl)}
        gt_doc = {"metadata": meta, "invoices": json_rows("ground_truth", gt),
                  "invoice_lines": json_rows("ground_truth_line", gtl)}
        files = write_dataset(root, final.tables, {"ground_truth/ground_truth.json": gt_doc,
                                                   "reports/validation_quick.json": report})
        write_file(root, "reports/validation_quick.md", _report_md(report, f"Quick validation ({alloc.scale})").encode(), files)
        dist = summarize(_strings(final.tables))
        write_file(root, "reports/distribution_summary.json", json_bytes(dist), files)
        write_file(root, "reports/distribution_summary.md",
                   to_markdown(dist, f"Distribution summary ({alloc.scale})").encode(), files)
        manifest = {
            "generator_version": P.GENERATOR_VERSION,
            "command": f"python -m invoice_ap generate --scale {scale} --seed {seed}",
            "seed": seed, "scale": alloc.scale, "factor": str(alloc.factor), "as_of_date": str(policy.as_of_date),
            "policy": {"id": policy.id, "version": policy.version, "sha256": policy.sha256},
            "baseline_validation": {"status": base_report["status"], "violations": base_report["violations"]},
            "provenance": {"data": "100% synthetic, generated by this repository from the seed above",
                           "external_sources": [], "personal_data": "none (role-labelled users, reserved .example domains)"},
            "pending": "inbox documents and their sha256/bytes in intake_manifest are produced in Stage 3",
            "files": {k: files[k] for k in sorted(files)},
        }
        write_file(root, "reports/source_manifest.json", json_bytes(manifest), {})
    return BuildResult(alloc, plan, baseline, final, base_report, report, files, root)
