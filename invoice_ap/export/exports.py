"""Exports of one built dataset (R32): JSON for every table and a SQL seed with PK / FK / CHECK
constraints, generated from the spec so the DDL can never drift from the data dictionary.

- `exports/json/<table>.json` for master, inbox and processed tables; `exports/json/evaluation/` for
  source and ground truth.
- `exports/sql/seed.sql`: DDL + INSERTs for master, inbox and processed (the engine's world).
- `exports/sql/evaluation_seed.sql`: DDL + INSERTs for source and ground truth, a separate file that
  is loaded after the seed, so labels never sit in the seed's input tables.

Everything is derived from the layer CSVs, in spec order, with LF line endings: byte-stable.
"""
from __future__ import annotations

import json
from pathlib import Path

from ..spec import BY_NAME, TABLES
from ..spec.io import read_table
from ..spec.model import TYPES

EVALUATION_LAYERS = ("source", "ground_truth")
SEED_LAYERS = ("master", "inbox", "processed")


def _typed(ftype: str, value: str):
    if ftype == "list":
        return [x for x in value.split("|") if x]
    if value == "":
        return None
    if ftype == "bool":
        return value == "true"
    if ftype == "int":
        return int(value)
    return value


def json_export(table: str, rows: list[dict[str, str]]) -> bytes:
    spec = BY_NAME[table]
    data = [{f.name: _typed(f.type, r[f.name]) for f in spec.fields} for r in rows]
    return (json.dumps(data, sort_keys=True, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")


# ------------------------------------------------------------------ SQL
def _quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _sql_value(ftype: str, value: str) -> str:
    if value == "":
        return "NULL"
    if ftype == "bool":
        return "1" if value == "true" else "0"
    if TYPES[ftype][1] in ("INTEGER", "NUMERIC"):
        return value
    return _quote(value)


def _column(f) -> str:
    parts = [f.name, TYPES[f.type][1]]
    if f.required:
        parts.append("NOT NULL")
    checks = []
    if f.type == "bool":
        checks.append(f"{f.name} IN (0, 1)")
    elif f.allowed and f.type != "list":
        checks.append(f"{f.name} IN ({', '.join(_quote(a) for a in f.allowed)})")
    if f.type == "date":
        checks.append(f"{f.name} = date({f.name})")
    if f.type == "datetime":
        checks.append(f"substr({f.name}, 1, 19) = strftime('%Y-%m-%dT%H:%M:%S', substr({f.name}, 1, 19))")
    if f.min_value and TYPES[f.type][1] in ("INTEGER", "NUMERIC"):
        checks.append(f"{f.name} >= {f.min_value}")
    if f.max_value and TYPES[f.type][1] in ("INTEGER", "NUMERIC"):
        checks.append(f"{f.name} <= {f.max_value}")
    if checks:
        parts.append("CHECK (" + " AND ".join(f"({c})" for c in checks) + f" OR {f.name} IS NULL)")
    return " ".join(parts)


def ddl(table: str) -> str:
    t = BY_NAME[table]
    lines = [_column(f) for f in t.fields]
    lines.append(f"PRIMARY KEY ({', '.join(t.primary_key)})")
    for f in t.fields:
        if f.unique and (f.name,) != tuple(t.primary_key):
            lines.append(f"UNIQUE ({f.name})")
    for group in t.unique_together:
        lines.append(f"UNIQUE ({', '.join(group)})")
    for f in t.fields:
        if f.fk:
            target, col = f.fk.split(".")
            lines.append(f"FOREIGN KEY ({f.name}) REFERENCES {target} ({col})")
    return f"CREATE TABLE {table} (\n  " + ",\n  ".join(lines) + "\n);\n"


def _order(tables: list[str]) -> list[str]:
    """Parents before children (FK order), ties in spec order."""
    names, done, out = list(tables), set(), []
    while names:
        for name in names:
            deps = {f.fk.split(".")[0] for f in BY_NAME[name].fields if f.fk} & set(tables)
            if deps - {name} <= done:
                out.append(name)
                done.add(name)
                names.remove(name)
                break
        else:
            raise ValueError(f"FK cycle among {names}")
    return out


def sql_script(tables: dict[str, list[dict[str, str]]], title: str) -> bytes:
    order = _order([t.name for t in TABLES if t.name in tables])
    out = [f"-- {title}", "-- Generated by `python -m invoice_ap export` from the spec and the layer CSVs.",
           "PRAGMA foreign_keys = ON;", "BEGIN TRANSACTION;", ""]
    for name in order:
        out.append(ddl(name))
    for name in order:
        fields = BY_NAME[name].fields
        cols = ", ".join(f.name for f in fields)
        for r in tables[name]:
            out.append(f"INSERT INTO {name} ({cols}) VALUES ("
                       + ", ".join(_sql_value(f.type, r[f.name]) for f in fields) + ");")
    out += ["COMMIT;", ""]
    return "\n".join(out).encode("utf-8")


def write_exports(root: Path) -> dict[str, int]:
    """Write every export of the dataset at `root`; returns {relative path: bytes}."""
    root = Path(root)
    tables = {t.name: read_table(root / t.layer, t.name) for t in TABLES if (root / t.file).exists()}
    written = {}

    def put(rel: str, data: bytes) -> None:
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written[rel] = len(data)
    for name, rows in tables.items():
        sub = "evaluation/" if BY_NAME[name].layer in EVALUATION_LAYERS else ""
        put(f"exports/json/{sub}{name}.json", json_export(name, rows))
    seed = {n: r for n, r in tables.items() if BY_NAME[n].layer in SEED_LAYERS}
    evaluation = {n: r for n, r in tables.items() if BY_NAME[n].layer in EVALUATION_LAYERS}
    put("exports/sql/seed.sql", sql_script(seed, "AP automation seed: master data, inbox and engine output"))
    put("exports/sql/evaluation_seed.sql", sql_script(
        evaluation, "Evaluation-only tables (source invoices, ground truth). Load after seed.sql."))
    return written
