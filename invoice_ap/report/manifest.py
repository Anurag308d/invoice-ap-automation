"""`reports/source_manifest.json` (R33): what a build contains and how to reproduce it.

Every file of the dataset is listed with its byte size, SHA-256 and row count, and whether it is
committed to git. Files left out of the commit by the size budget (about 25 MB)
keep their checksum here, so a rebuild can be verified against it. The reproducibility report is
written after the manifest and is not listed in it (it describes the build rather than being part
of it).
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

GENERATOR_VERSION_KEYS = ("generator_version", "seed", "scale", "factor", "as_of_date", "policy",
                          "baseline_validation", "documents")
NOT_LISTED = ("reports/source_manifest.json", "reports/reproducibility.json", "reports/reproducibility.md")
# Full-scale files regenerated by `build-all` instead of committed (size budget, in ruling order).
EXCLUDED_FROM_COMMIT = {"full": ("exports/json/", "exports/sql/", "processed/decision_trace.jsonl",
                                 "processed/extraction_field.csv")}
PROVENANCE = {
    "data": "100% synthetic, generated by this repository from the seed above; no external, scraped or real data",
    "external_sources": [],
    "personal_data": "none: role-labelled users, reserved .example domains, invented vendor names and tax numbers",
    "licences": {"code": "MIT (LICENSE)", "generated_data": "MIT, as part of this repository",
                 "third_party": "none at runtime (Python standard library only); pytest for tests"},
}


def _rows(path: Path, rel: str) -> int | None:
    if rel.endswith(".csv"):
        with open(path, newline="", encoding="utf-8") as fh:
            return sum(1 for _ in csv.reader(fh)) - 1
    if rel.endswith(".jsonl"):
        return sum(1 for _ in open(path, encoding="utf-8"))
    if rel.endswith(".json") and rel.startswith(("exports/", "ground_truth/")):
        obj = json.loads(path.read_text(encoding="utf-8"))
        return len(obj) if isinstance(obj, list) else len(obj.get("invoices", []))
    return None


def is_excluded(scale: str, rel: str) -> bool:
    return any(rel == p or (p.endswith("/") and rel.startswith(p)) for p in EXCLUDED_FROM_COMMIT.get(scale, ()))


def file_table(root: Path) -> dict[str, dict]:
    out = {}
    for path in sorted(Path(root).rglob("*")):
        rel = path.relative_to(root).as_posix()
        if path.is_file() and rel not in NOT_LISTED:
            data = path.read_bytes()
            entry = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
            rows = _rows(path, rel)
            if rows is not None:
                entry["rows"] = rows
            out[rel] = entry
    return out


def tree_digest(files: dict[str, dict]) -> str:
    return hashlib.sha256("".join(f"{k}:{v['sha256']}\n" for k, v in sorted(files.items())).encode()).hexdigest()


def write_manifest(root: Path, policy) -> dict:
    root = Path(root)
    path = root / "reports" / "source_manifest.json"
    generated = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    head = {k: generated[k] for k in GENERATOR_VERSION_KEYS if k in generated}
    scale, seed = head.get("scale", root.name), head.get("seed")
    files = file_table(root)
    for rel, entry in files.items():
        entry["committed"] = not is_excluded(scale, rel)
    excluded = {rel: e for rel, e in files.items() if not e["committed"]}
    manifest = {
        **head,
        "command": {"everything": "python -m invoice_ap build-all",
                    "this_scale": f"python -m invoice_ap build --scale {scale} --seed {seed}",
                    "steps": ["generate", "run", "evaluate", "validate", "export", "dashboard", "manifest"]},
        "policy": {"id": policy.id, "version": policy.version, "sha256": policy.sha256},
        "provenance": PROVENANCE,
        "label_separation": {
            "engine_inputs": ["master/", "inbox/"],
            "evaluation_only": ["source/", "ground_truth/", "exports/json/evaluation/", "exports/sql/evaluation_seed.sql"],
            "sql": "exports/sql/seed.sql holds master, inbox and processed tables only; ground truth and source "
                   "invoices are in exports/sql/evaluation_seed.sql, loaded after it"},
        "commit_policy": {"excluded_from_commit": list(EXCLUDED_FROM_COMMIT.get(scale, ())),
                          "reason": "repository size budget (about 25 MB); "
                                    "regenerate with `python -m invoice_ap build-all` and verify against the "
                                    "checksums below",
                          "excluded_files": len(excluded),
                          "excluded_bytes": sum(e["bytes"] for e in excluded.values())},
        "totals": {"files": len(files), "bytes": sum(e["bytes"] for e in files.values()),
                   "committed_bytes": sum(e["bytes"] for e in files.values() if e["committed"]),
                   "tree_sha256": tree_digest(files)},
        "files": files,
    }
    path.write_text(json.dumps(manifest, indent=1, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
    return manifest
